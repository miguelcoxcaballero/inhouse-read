import {test,expect} from '@playwright/test'
import {fakeEngineScript} from '../helpers/fake-neural-engine.js'
for(const [format,width] of [['pdf',320],['epub',390]]) test(`reading pages and remaining audio fit ${format} at ${width}px`,async({page})=>{
 test.setTimeout(120000)
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.setViewportSize({width,height:844})
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.addInitScript(fakeEngineScript({installed:['piper:en_US-lessac-high'],hold:true}))
 await page.addInitScript(()=>localStorage.setItem('inhouse-read-reading-preferences',JSON.stringify({pdfMode:'text'})))
 await page.goto('./')
 await page.locator('#file-picker').setInputFiles(`tests/e2e/fixtures/reading-journey.${format}`)
 const counter=page.locator('.reader-location-label')
 await expect(counter).toHaveText(/\d+ % · \d+\/\d+/)
 const initial=await counter.textContent()
 await expect(page.locator('.reading-mini-player')).toBeHidden()
 const box=await counter.boundingBox()
 expect(box.x).toBeGreaterThanOrEqual(0)
 expect(box.x+box.width).toBeLessThan(width)
 expect(await counter.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
 await page.locator('#reader-next').click()
 if(format==='pdf') await expect(counter).toContainText('2/4')
 await page.locator('#reader-audio').click()
 const panelTime=page.locator('.reading-panel [data-audio-remaining]')
 await expect(panelTime).toHaveText(/\d+h \d{2}min/)
 await expect(panelTime).toHaveAttribute('aria-label',/Tiempo restante estimado/)
 await page.locator('[data-rate][value="2"]').check()
 await expect(panelTime).not.toContainText('—')
 await page.locator('[data-play]').click()
 await page.locator('[data-close]').click()
 const miniTime=page.locator('.reading-mini-player [data-audio-remaining]')
 await expect(miniTime).toBeVisible()
 await expect(miniTime).toHaveText(/\d+h \d{2}min/)
 // Expose the existing return destination as well: it must never cover time/play/stop.
 await page.evaluate(()=>{const link=document.querySelector('.reader-return');link.hidden=false;link.textContent='↶ Volver al audio'})
 const link=await page.locator('.reader-return').boundingBox(),time=await miniTime.boundingBox(),play=await page.locator('[data-mini-play]').boundingBox()
 expect(link.x+link.width).toBeLessThanOrEqual(time.x+1)
 expect(time.x+time.width).toBeLessThanOrEqual(play.x+1)
 await page.screenshot({path:`test-results/reader-metrics-${format}-${width}.png`})
 await page.locator('[data-mini-stop]').click()
 await expect(page.locator('.reading-mini-player')).toBeHidden()
 await expect(counter).toHaveText(/\d+ % · \d+\/\d+/)
 expect(initial).toMatch(/\d+\/\d+/)
 expect(errors).toEqual([])
})
