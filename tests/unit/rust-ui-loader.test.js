import {beforeEach,afterEach,it,expect,vi} from 'vitest'
const mock=vi.hoisted(()=>({init:vi.fn(),abi:vi.fn(),Menu:class{}}))
vi.mock('../../src/wasm/ui/inhouse_read_ui.js',()=>({default:mock.init,ui_abi_version:mock.abi,RustSelectMenu:mock.Menu}))
beforeEach(()=>{vi.resetModules();vi.useFakeTimers();mock.init.mockReset().mockResolvedValue({});mock.abi.mockReset().mockReturnValue(1)})
afterEach(()=>vi.useRealTimers())
it('shares one module initialization across concurrent readers',async()=>{
 const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js');expect(getRustUI()).toBe(null)
 const a=loadRustUI(),b=loadRustUI();expect(a).toBe(b)
 const ui=await a;expect(ui.RustSelectMenu).toBe(mock.Menu);expect(getRustUI()).toBe(ui);expect(await loadRustUI()).toBe(ui);expect(mock.init).toHaveBeenCalledTimes(1)
})
it('retains controls after a download error and retries only after cooldown',async()=>{
 mock.init.mockRejectedValueOnce(new Error('offline'))
 const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js')
 expect(await loadRustUI()).toBe(null);expect(getRustUI()).toBe(null);expect(await loadRustUI()).toBe(null);expect(mock.init).toHaveBeenCalledTimes(1)
 vi.advanceTimersByTime(30001);expect((await loadRustUI()).RustSelectMenu).toBe(mock.Menu);expect(mock.init).toHaveBeenCalledTimes(2)
})
it('rejects an incompatible module before exposing any component',async()=>{
 mock.abi.mockReturnValue(2);const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js')
 expect(await loadRustUI()).toBe(null);expect(getRustUI()).toBe(null)
})
it('does not block opening a book indefinitely when a module request stalls',async()=>{
 let finish;mock.init.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}))
 const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js'),loading=loadRustUI()
 await vi.advanceTimersByTimeAsync(2000);expect(await loading).toBe(null);expect(getRustUI()).toBe(null)
 finish({});await vi.advanceTimersByTimeAsync(0);expect(getRustUI().RustSelectMenu).toBe(mock.Menu)
 expect((await loadRustUI()).RustSelectMenu).toBe(mock.Menu);expect(mock.init).toHaveBeenCalledTimes(1)
})
it('reuses a still-pending initializer after the retry window instead of replacing its memory',async()=>{
 let finish;mock.init.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}))
 const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js'),first=loadRustUI()
 await vi.advanceTimersByTimeAsync(2000);expect(await first).toBe(null)
 await vi.advanceTimersByTimeAsync(30001);const second=loadRustUI()
 await vi.advanceTimersByTimeAsync(0);expect(mock.init).toHaveBeenCalledTimes(1)
 finish({});expect((await second).RustSelectMenu).toBe(mock.Menu);expect(getRustUI().RustSelectMenu).toBe(mock.Menu)
})
it('does not expose an incompatible late result and can retry after it fails',async()=>{
 let finish;mock.init.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}));mock.abi.mockReturnValueOnce(2)
 const {loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js'),first=loadRustUI()
 await vi.advanceTimersByTimeAsync(2000);expect(await first).toBe(null)
 finish({});await vi.advanceTimersByTimeAsync(0);expect(getRustUI()).toBe(null)
 await vi.advanceTimersByTimeAsync(30001);expect((await loadRustUI()).RustSelectMenu).toBe(mock.Menu)
 expect(mock.init).toHaveBeenCalledTimes(2)
})

it('notifies late components once after the startup deadline and skips disposed listeners',async()=>{
 let finish;mock.init.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}))
 const {loadRustUI}=await import('../../src/js/rust-ui.js')
 const {onRustUIReady}=await import('../../src/js/rust-ui-readiness.js')
 const loaded=vi.fn(),disposed=vi.fn();onRustUIReady(loaded);const cancel=onRustUIReady(disposed);cancel()
 const pending=loadRustUI();await vi.advanceTimersByTimeAsync(2000);expect(await pending).toBeNull();expect(loaded).not.toHaveBeenCalled()
 finish({});await vi.advanceTimersByTimeAsync(0);expect(loaded).toHaveBeenCalledOnce();expect(disposed).not.toHaveBeenCalled()
 await loadRustUI();expect(loaded).toHaveBeenCalledOnce()
})
it('does not lose other components or reject a valid module when one readiness listener throws',async()=>{
 const {loadRustUI}=await import('../../src/js/rust-ui.js')
 const {onRustUIReady}=await import('../../src/js/rust-ui-readiness.js')
 const ready=vi.fn();onRustUIReady(()=>{throw Error('component')});onRustUIReady(ready)
 expect(await loadRustUI()).not.toBeNull();expect(ready).toHaveBeenCalledOnce()
})
it('requireRustUI is the loaded module at once and never starts a second initialization',async()=>{
 const {requireRustUI,loadRustUI}=await import('../../src/js/rust-ui.js')
 const first=await requireRustUI();expect(first.RustSelectMenu).toBe(mock.Menu);expect(await requireRustUI()).toBe(first);expect(await loadRustUI()).toBe(first);expect(mock.init).toHaveBeenCalledOnce()
})
it('requireRustUI keeps waiting for the same download after the 2 s release of other callers',async()=>{
 let finish;mock.init.mockImplementationOnce(()=>new Promise(resolve=>{finish=resolve}))
 const {requireRustUI,loadRustUI,getRustUI}=await import('../../src/js/rust-ui.js')
 const reader=requireRustUI(),other=loadRustUI()
 await vi.advanceTimersByTimeAsync(2000);expect(await other).toBeNull();expect(getRustUI()).toBeNull()
 await vi.advanceTimersByTimeAsync(20_000);expect(getRustUI()).toBeNull()
 finish({});const ui=await reader;expect(ui.RustSelectMenu).toBe(mock.Menu);expect(getRustUI()).toBe(ui);expect(mock.init).toHaveBeenCalledOnce()
})
it('requireRustUI reports a download that never finishes 30 s after the release, without a second instance',async()=>{
 mock.init.mockImplementationOnce(()=>new Promise(()=>{}))
 const {requireRustUI,getRustUI}=await import('../../src/js/rust-ui.js')
 const reader=requireRustUI();await vi.advanceTimersByTimeAsync(2000+30_000)
 expect(await reader).toBeNull();expect(getRustUI()).toBeNull();expect(mock.init).toHaveBeenCalledOnce()
})
it('requireRustUI reports a failed module immediately and retries after the cooldown',async()=>{
 mock.init.mockRejectedValueOnce(new Error('offline'))
 const {requireRustUI}=await import('../../src/js/rust-ui.js')
 expect(await requireRustUI()).toBeNull();expect(await requireRustUI()).toBeNull();expect(mock.init).toHaveBeenCalledOnce()
 await vi.advanceTimersByTimeAsync(30_001);expect((await requireRustUI()).RustSelectMenu).toBe(mock.Menu);expect(mock.init).toHaveBeenCalledTimes(2)
})
